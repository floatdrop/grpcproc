// Package protocgen writes the Go of a process's contract: for a service
// marked with grpcproc.v1.process, an address whose methods are its rpcs,
// a handler interface with one per rpc, the dispatch from a message to it,
// and a way to each topic the process owns. cmd/protoc-gen-grpcproc runs
// it.
package protocgen

import (
	"fmt"
	"go/token"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"

	grpcprocv1 "github.com/floatdrop/grpcproc/proto/grpcproc/v1"
)

// Suffix is what a generated file's name ends with, after the proto's.
const Suffix = "_grpcproc.pb.go"

const (
	grpcprocPkg = protogen.GoImportPath("github.com/floatdrop/grpcproc")
	pubsubPkg   = protogen.GoImportPath("github.com/floatdrop/grpcproc/pubsub")
	contextPkg  = protogen.GoImportPath("context")
	timePkg     = protogen.GoImportPath("time")
	protoPkg    = protogen.GoImportPath("google.golang.org/protobuf/proto")
)

const emptyMessage protoreflect.FullName = "google.protobuf.Empty"

// reserved are the names an rpc may not have: grpcproc.Addr's methods,
// which a generated address method would shadow, and the actor's lifecycle
// methods, which a handler method would collide with on the actor.
var reserved = []string{
	"Addr", "Call", "CallLink", "CallMonitor", "Name", "Node", "PID", "Send", "String",
	"HandleCall", "HandleDown", "HandleExited", "HandleMessage", "Init", "Terminate",
}

// Generate writes a file for each file given that has a service marked as
// a process, beside protoc-gen-go's. It is what protogen.Options.Run is
// given.
func Generate(gen *protogen.Plugin) error {
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
	gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO2
	gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2023
	for _, f := range gen.Files {
		if !f.Generate {
			continue
		}
		if err := generateFile(gen, f); err != nil {
			return err
		}
	}
	return nil
}

func generateFile(gen *protogen.Plugin, f *protogen.File) error {
	var services []*protogen.Service
	for _, s := range f.Services {
		if proto.HasExtension(s.Desc.Options(), grpcprocv1.E_Process) {
			services = append(services, s)
		}
	}
	if len(services) == 0 {
		return nil
	}
	// What the file declares already, which nothing generated may be named
	// as: protoc-gen-go's messages and enums, and the other services' code.
	taken := map[string]string{}
	var messages func(ms []*protogen.Message)
	messages = func(ms []*protogen.Message) {
		for _, m := range ms {
			taken[m.GoIdent.GoName] = "message " + string(m.Desc.FullName())
			for _, e := range m.Enums {
				taken[e.GoIdent.GoName] = "enum " + string(e.Desc.FullName())
			}
			for _, o := range m.Oneofs {
				for _, f := range o.Fields {
					taken[f.GoIdent.GoName] = "oneof field " + string(f.Desc.FullName())
				}
			}
			messages(m.Messages)
		}
	}
	messages(f.Messages)
	for _, e := range f.Enums {
		taken[e.GoIdent.GoName] = "enum " + string(e.Desc.FullName())
	}
	names := map[string]string{} // the names the file's processes and topics register under
	var checked []*service
	for _, s := range services {
		svc, err := check(s)
		if err != nil {
			return err
		}
		for _, ident := range svc.idents() {
			if by, ok := taken[ident]; ok {
				return fmt.Errorf("%s: it would generate %s, which %s is named already", s.Desc.FullName(), ident, by)
			}
			taken[ident] = "service " + string(s.Desc.FullName())
		}
		for _, r := range svc.registers() {
			if by, ok := names[r.name]; ok {
				return fmt.Errorf("%s: %s registers as %q, which %s does too", s.Desc.FullName(), r.by, r.name, by)
			}
			names[r.name] = r.by
		}
		checked = append(checked, svc)
	}
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+Suffix, f.GoImportPath)
	g.P("// Code generated by protoc-gen-grpcproc. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	for _, svc := range checked {
		generateService(g, svc)
	}
	return nil
}

// kind is what an rpc stands for.
type kind int

const (
	call  kind = iota // answered with its response
	send              // taken, and answered nothing
	topic             // a pubsub topic the process owns, of the response type
)

// rpc is one method of a service, checked.
type rpc struct {
	m     *protogen.Method
	kind  kind
	empty bool   // the request has no fields: it is left out of the signatures
	topic string // the topic's name, for a topic
}

// service is a service marked as a process, checked: what the generated
// identifiers are made from and how its processes are named.
type service struct {
	s      *protogen.Service
	name   string // the Go name
	fixed  string // the registered name, for a process with one
	prefix string // the prefix of the registered names, for processes named per instance
	rpcs   []rpc
}

func check(s *protogen.Service) (*service, error) {
	opts, _ := proto.GetExtension(s.Desc.Options(), grpcprocv1.E_Process).(*grpcprocv1.ProcessOptions)
	if opts.GetName() != "" && opts.GetPrefix() != "" {
		return nil, fmt.Errorf("%s: a process has a name or a prefix, not both", s.Desc.FullName())
	}
	out := &service{s: s, name: s.GoName, fixed: opts.GetName(), prefix: opts.GetPrefix()}
	if goName := opts.GetGoName(); goName != "" {
		if !token.IsIdentifier(goName) || !token.IsExported(goName) {
			return nil, fmt.Errorf("%s: go_name %q is not an exported Go identifier", s.Desc.FullName(), goName)
		}
		out.name = goName
	}
	inputs := map[kind]map[protoreflect.FullName]string{call: {}, send: {}} // by kind: the rpc that takes each message
	topics := map[string]string{}                                           // by topic name: the rpc
	methods := map[string]string{}                                          // by method of the address: the rpc
	for _, m := range s.Methods {
		if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
			return nil, fmt.Errorf("%s: a process takes messages and answers calls: no streaming", m.Desc.FullName())
		}
		r := rpc{m: m, empty: m.Desc.Input().Fields().Len() == 0 && m.Desc.Input().ExtensionRanges().Len() == 0}
		isSend, _ := proto.GetExtension(m.Desc.Options(), grpcprocv1.E_Send).(bool)
		if t, ok := proto.GetExtension(m.Desc.Options(), grpcprocv1.E_Topic).(*grpcprocv1.TopicOptions); ok && t != nil {
			switch {
			case isSend:
				return nil, fmt.Errorf("%s: a topic is not a send: one option or the other", m.Desc.FullName())
			case t.GetName() == "":
				return nil, fmt.Errorf("%s: a topic needs a name", m.Desc.FullName())
			case m.Desc.Input().FullName() != emptyMessage:
				return nil, fmt.Errorf("%s: a topic takes %s and returns its events: it takes %s", m.Desc.FullName(), emptyMessage, m.Desc.Input().FullName())
			case out.fixed == "" && out.prefix == "":
				return nil, fmt.Errorf("%s: a topic is named after its process, which has no name and no prefix", m.Desc.FullName())
			}
			if other, ok := topics[t.GetName()]; ok {
				return nil, fmt.Errorf("%s: %s is the topic %q too", m.Desc.FullName(), other, t.GetName())
			}
			topics[t.GetName()] = m.GoName
			r.kind, r.topic = topic, t.GetName()
			out.rpcs = append(out.rpcs, r)
			continue
		}
		if slices.Contains(reserved, m.GoName) {
			return nil, fmt.Errorf("%s: an rpc may not be named as a method of grpcproc.Addr or of an actor: %s", m.Desc.FullName(), strings.Join(reserved, ", "))
		}
		generated := []string{m.GoName}
		if isSend {
			if m.Desc.Output().FullName() != emptyMessage {
				return nil, fmt.Errorf("%s: a send answers nothing: it returns %s, not %s", m.Desc.FullName(), emptyMessage, m.Desc.Output().FullName())
			}
			r.kind = send
			generated = append(generated, m.GoName+"After")
		}
		for _, method := range generated {
			if other, ok := methods[method]; ok {
				return nil, fmt.Errorf("%s: it would generate the method %s, which %s does too", m.Desc.FullName(), method, other)
			}
			methods[method] = m.GoName
		}
		if other, taken := inputs[r.kind][m.Desc.Input().FullName()]; taken {
			return nil, fmt.Errorf("%s: %s takes %s too: a message is dispatched by its type, to one rpc", m.Desc.FullName(), other, m.Desc.Input().FullName())
		}
		inputs[r.kind][m.Desc.Input().FullName()] = m.GoName
		out.rpcs = append(out.rpcs, r)
	}
	return out, nil
}

// idents are the identifiers the service's code declares in its package.
func (svc *service) idents() []string {
	name := svc.name
	out := []string{name + "Addr", name + "AddrOf", name + "Handler", "Handle" + name + "Call", "Handle" + name + "Message", "Unimplemented" + name + "Handler"}
	if svc.fixed != "" || svc.prefix != "" {
		out = append(out, name+"Process", name+"At", name+"Global")
	}
	for _, r := range svc.rpcs {
		if r.kind == topic {
			out = append(out, name+r.m.GoName+"Topic", name+r.m.GoName+"At")
		}
	}
	return out
}

// registered is one name a process or a topic registers under on a node,
// and what registers it.
type registered struct{ name, by string }

// registers is the names the service's process and topics register under,
// for a process with a fixed name; those of a process named per instance
// differ by the id and cannot clash.
func (svc *service) registers() []registered {
	if svc.fixed == "" {
		return nil
	}
	out := []registered{{svc.fixed, "the " + svc.name + " process"}}
	for _, r := range svc.rpcs {
		if r.kind == topic {
			out = append(out, registered{r.topic, "the " + r.m.GoName + " topic of " + svc.name})
		}
	}
	return out
}

// names are the Go identifiers a service's code is written with.
type names struct {
	addr, process, msg, caller, ctx, message string
}

func generateService(g *protogen.GeneratedFile, svc *service) {
	s := svc.s
	name := svc.name
	client, server := name+"Addr", name+"Handler"
	message := g.QualifiedGoIdent(protoPkg.Ident("Message"))
	id := names{
		addr:    g.QualifiedGoIdent(grpcprocPkg.Ident("Addr")) + "[" + message + "]",
		process: g.QualifiedGoIdent(grpcprocPkg.Ident("Process")) + "[" + message + "]",
		msg:     g.QualifiedGoIdent(grpcprocPkg.Ident("Msg")) + "[" + message + "]",
		caller:  g.QualifiedGoIdent(grpcprocPkg.Ident("Caller")),
		ctx:     g.QualifiedGoIdent(contextPkg.Ident("Context")),
		message: message,
	}

	// The registered names, and the constructors from them.
	switch {
	case svc.fixed != "":
		g.P("// ", name, "Process is the name a process of the ", name, " service is registered under on its node.")
		g.P("const ", name, "Process = ", fmt.Sprintf("%q", svc.fixed))
		g.P()
	case svc.prefix != "":
		g.P("// ", name, "Process is the name the process of the ", name, " service for id is registered under on its node.")
		g.P("func ", name, "Process(id string) string { return ", fmt.Sprintf("%q", svc.prefix), " + id }")
		g.P()
	}
	g.P("// ", client, " addresses a process of the ", name, " service; its methods are its rpcs.")
	doc(g, s.Comments)
	g.P("type ", client, " struct{ ", id.addr, " }")
	g.P()
	g.P("// ", client, "Of addresses t, a PID, a Name or a global name, as a process of the ", name, " service.")
	g.P("func ", client, "Of(t ", g.QualifiedGoIdent(grpcprocPkg.Ident("Target")), ") ", client, " {")
	g.P("return ", client, "{", g.QualifiedGoIdent(grpcprocPkg.Ident("AddrOf")), "[", message, "](t)}")
	g.P("}")
	g.P()
	named, global := g.QualifiedGoIdent(grpcprocPkg.Ident("Name")), g.QualifiedGoIdent(grpcprocPkg.Ident("Global"))
	switch {
	case svc.fixed != "":
		g.P("// ", name, "At addresses the process of the ", name, " service on node, registered as ", name, "Process.")
		g.P("func ", name, "At(node string) ", client, " {")
		g.P("return ", client, "Of(", named, "{Node: node, Name: ", name, "Process})")
		g.P("}")
		g.P()
		g.P("// ", name, "Global addresses the process of the ", name, " service that holds the global name ", name, "Process, wherever it runs.")
		g.P("func ", name, "Global() ", client, " {")
		g.P("return ", client, "Of(", global, "{Name: ", name, "Process})")
		g.P("}")
		g.P()
	case svc.prefix != "":
		g.P("// ", name, "At addresses the process of the ", name, " service for id on node, registered as ", name, "Process(id).")
		g.P("func ", name, "At(node, id string) ", client, " {")
		g.P("return ", client, "Of(", named, "{Node: node, Name: ", name, "Process(id)})")
		g.P("}")
		g.P()
		g.P("// ", name, "Global addresses the process of the ", name, " service that holds the global name ", name, "Process(id), wherever it runs.")
		g.P("func ", name, "Global(id string) ", client, " {")
		g.P("return ", client, "Of(", global, "{Name: ", name, "Process(id)})")
		g.P("}")
		g.P()
	}

	// The topics.
	for _, r := range svc.rpcs {
		if r.kind != topic {
			continue
		}
		topicName, event := name+r.m.GoName+"Topic", g.QualifiedGoIdent(r.m.Output.GoIdent)
		typ := g.QualifiedGoIdent(pubsubPkg.Ident("Topic")) + "[*" + event + "]"
		if svc.fixed != "" {
			g.P("// ", topicName, " is the name the ", r.m.GoName, " topic of the ", name, " service is registered under on its process's node.")
			g.P("const ", topicName, " = ", fmt.Sprintf("%q", r.topic))
			g.P()
			g.P("// ", name, r.m.GoName, "At is the ", r.m.GoName, " topic of the ", name, " service on node, whose events are ", r.m.Output.GoIdent.GoName, ".")
			doc(g, r.m.Comments)
			g.P("func ", name, r.m.GoName, "At(node string) ", typ, " {")
			g.P("return ", g.QualifiedGoIdent(pubsubPkg.Ident("Named")), "[*", event, "](node, ", topicName, ")")
		} else {
			g.P("// ", topicName, " is the name the ", r.m.GoName, " topic of the ", name, " service's process for id is registered under on its node.")
			g.P("func ", topicName, "(id string) string { return ", name, "Process(id) + ", fmt.Sprintf("%q", "/"+r.topic), " }")
			g.P()
			g.P("// ", name, r.m.GoName, "At is the ", r.m.GoName, " topic of the ", name, " service's process for id on node, whose events are ", r.m.Output.GoIdent.GoName, ".")
			doc(g, r.m.Comments)
			g.P("func ", name, r.m.GoName, "At(node, id string) ", typ, " {")
			g.P("return ", g.QualifiedGoIdent(pubsubPkg.Ident("Named")), "[*", event, "](node, ", topicName, "(id))")
		}
		g.P("}")
		g.P()
	}

	// The address's methods.
	for _, r := range svc.rpcs {
		if r.kind == topic {
			continue
		}
		in := g.QualifiedGoIdent(r.m.Input.GoIdent)
		req, arg := ", req *"+in, "req"
		if r.empty {
			req, arg = "", "&"+in+"{}"
		}
		if r.kind == send {
			g.P(leading(r.m.Comments, "// "+r.m.GoName+" sends "+describe(r)+" to the process, which answers nothing."))
			g.P("func (c ", client, ") ", r.m.GoName, "(ctx ", id.ctx, ", from ", id.caller, req, ") error {")
			g.P("return c.Send(ctx, from, ", arg, ")")
			g.P("}")
			g.P()
			g.P("// ", r.m.GoName, "After sends ", describe(r), " to the process after d, from p; the timer can stop it.")
			g.P("func (c ", client, ") ", r.m.GoName, "After[M ", id.message, "](p *", g.QualifiedGoIdent(grpcprocPkg.Ident("Process")), "[M], d ", g.QualifiedGoIdent(timePkg.Ident("Duration")), req, ") *", g.QualifiedGoIdent(grpcprocPkg.Ident("Timer")), " {")
			g.P("return p.SendAfter(d, c.Addr, ", id.message, "(", arg, "))")
		} else {
			out := g.QualifiedGoIdent(r.m.Output.GoIdent)
			g.P(leading(r.m.Comments, "// "+r.m.GoName+" calls the process with "+describe(r)+" and waits for its "+r.m.Output.GoIdent.GoName+"."))
			g.P("func (c ", client, ") ", r.m.GoName, "(ctx ", id.ctx, ", from ", id.caller, req, ") (*", out, ", error) {")
			g.P("return c.Call[*", out, "](ctx, from, ", arg, ")")
		}
		g.P("}")
		g.P()
	}

	// The handler, its dispatch, and the implementation of nothing.
	g.P("// ", server, " is what a process of the ", name, " service does with what it is")
	g.P("// sent: a method per call, whose result is the reply, as actor.CallHandler's")
	g.P("// is, and one per send. Handle", name, "Call and Handle", name, "Message dispatch to it;")
	g.P("// Unimplemented", server, " answers for the methods an implementation leaves out.")
	g.P("type ", server, " interface {")
	for _, r := range svc.rpcs {
		if r.kind != topic {
			g.P(r.m.GoName, "(p *", id.process, ", m ", id.msg, handlerReq(g, r, true), ") ", handlerResult(g, r))
		}
	}
	g.P("}")
	g.P()
	g.P("// Handle", name, "Call answers a call to a process of the ", name, " service through s,")
	g.P("// for an actor.CallHandler's HandleCall; a call of another type is answered")
	g.P("// grpcproc.ErrType.")
	g.P("func Handle", name, "Call(s ", server, ", p *", id.process, ", m ", id.msg, ") (", message, ", error) {")
	dispatch(g, svc.rpcs, call)
	g.P("return nil, ", g.QualifiedGoIdent(grpcprocPkg.Ident("ErrType")))
	g.P("}")
	g.P()
	g.P("// Handle", name, "Message takes a send to a process of the ", name, " service through s,")
	g.P("// for an actor.Handler's HandleMessage; a message of another type is logged")
	g.P("// and dropped, as actor.CallsOnly drops one. A message the process takes")
	g.P("// from elsewhere, a topic's events say, is declared as a send too.")
	g.P("func Handle", name, "Message(s ", server, ", p *", id.process, ", m ", id.msg, ") error {")
	dispatch(g, svc.rpcs, send)
	g.P(`p.Log().Warn("`, lowerFirst(name), `: dropped a message that is not one of its sends", "from", m.From, "type", `, g.QualifiedGoIdent(protoPkg.Ident("MessageName")), "(m.Body))")
	g.P("return nil")
	g.P("}")
	g.P()
	g.P("// Unimplemented", server, " answers grpcproc.ErrType to every call and drops every send,")
	g.P("// for an implementation to embed and override what it handles.")
	g.P("type Unimplemented", server, " struct{}")
	g.P()
	for _, r := range svc.rpcs {
		if r.kind == topic {
			continue
		}
		if r.kind == send {
			g.P("func (Unimplemented", server, ") ", r.m.GoName, "(p *", id.process, ", m ", id.msg, handlerReq(g, r, true), ") error {")
			g.P(`p.Log().Warn("`, lowerFirst(name), `: dropped `, r.m.GoName, `, which is not implemented", "from", m.From)`)
			g.P("return nil")
		} else {
			g.P("func (Unimplemented", server, ") ", r.m.GoName, "(*", id.process, ", ", id.msg, handlerReq(g, r, false), ") ", handlerResult(g, r), " {")
			g.P("return nil, ", g.QualifiedGoIdent(grpcprocPkg.Ident("ErrType")))
		}
		g.P("}")
		g.P()
	}
}

// handlerReq is the request parameter of a handler method, named req or
// not: none for a request with no fields.
func handlerReq(g *protogen.GeneratedFile, r rpc, named bool) string {
	if r.empty {
		return ""
	}
	if named {
		return ", req *" + g.QualifiedGoIdent(r.m.Input.GoIdent)
	}
	return ", *" + g.QualifiedGoIdent(r.m.Input.GoIdent)
}

// handlerResult is what a handler method returns: the reply for a call.
func handlerResult(g *protogen.GeneratedFile, r rpc) string {
	if r.kind == send {
		return "error"
	}
	return "(*" + g.QualifiedGoIdent(r.m.Output.GoIdent) + ", error)"
}

// describe says what a method sends: req, or the message's name when it
// has no fields and is not passed.
func describe(r rpc) string {
	if r.empty {
		return "a " + r.m.Input.GoIdent.GoName
	}
	return "req"
}

// dispatch writes the type switch over m.Body that hands the rpcs of kind k
// to s; nothing when there are none.
func dispatch(g *protogen.GeneratedFile, rpcs []rpc, k kind) {
	var cases []rpc
	for _, r := range rpcs {
		if r.kind == k {
			cases = append(cases, r)
		}
	}
	if len(cases) == 0 {
		return
	}
	if slices.ContainsFunc(cases, func(r rpc) bool { return !r.empty }) {
		g.P("switch req := m.Body.(type) {")
	} else {
		g.P("switch m.Body.(type) {")
	}
	for _, r := range cases {
		g.P("case *", g.QualifiedGoIdent(r.m.Input.GoIdent), ":")
		if r.empty {
			g.P("return s.", r.m.GoName, "(p, m)")
		} else {
			g.P("return s.", r.m.GoName, "(p, m, req)")
		}
	}
	g.P("}")
}

// doc writes c's leading comment as a further paragraph of a doc comment.
func doc(g *protogen.GeneratedFile, c protogen.CommentSet) {
	if text := trimmed(c); text != "" {
		g.P("//")
		g.P(text)
	}
}

// trimmed is c's leading comment as Go comment lines, "" when there is
// none.
func trimmed(c protogen.CommentSet) string {
	if strings.TrimSpace(string(c.Leading)) == "" {
		return ""
	}
	return strings.TrimSuffix(c.Leading.String(), "\n")
}

// leading is the comment a declaration gets: the proto's leading comment,
// or fallback when it has none.
func leading(c protogen.CommentSet, fallback string) string {
	if text := trimmed(c); text != "" {
		return text
	}
	return fallback
}

func lowerFirst(s string) string {
	r, n := utf8.DecodeRuneInString(s)
	return string(unicode.ToLower(r)) + s[n:]
}
